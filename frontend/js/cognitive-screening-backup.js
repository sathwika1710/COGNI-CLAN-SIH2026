// CATEGORY RESULTS
// ============================================================

function createCategoryResults() {

    categoryList.innerHTML =
        "";


    const categories = {};


    // --------------------------------------------------------
    // GROUP
    // --------------------------------------------------------

    symptoms.forEach(
        function(
            symptom,
            index
        ) {


            const category =
                symptom.category;


            if (
                !categories[category]
            ) {

                categories[category] = {

                    total:
                        0,

                    count:
                        0

                };

            }


            categories[category].total +=
                answers[index] || 0;


            categories[category].count++;

        }
    );


    // --------------------------------------------------------
    // DISPLAY
    // --------------------------------------------------------

    Object.keys(
        categories
    ).forEach(
        function(category) {


            const data =
                categories[category];


            const max =
                data.count * 3;


            const percentage =
                Math.round(
                    (data.total / max) *
                    100
                );


            const item =
                document.createElement(
                    "div"
                );


            item.className =
                "category-item";


            item.innerHTML = `

                <div class="category-top">

                    <span>
                        ${getCategoryText(
                            category
                        )}
                    </span>

                    <span>
                        ${percentage}%
                    </span>

                </div>


                <div class="category-bar">

                    <div
                        class="category-fill"
                        style="width: ${percentage}%"
                    ></div>

                </div>

            `;


            categoryList.appendChild(
                item
            );

        }
    );

}


