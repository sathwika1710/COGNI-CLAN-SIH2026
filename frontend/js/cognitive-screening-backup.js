// SAVE SCREENING RESULT
// ============================================================

async function saveScreeningResult(
    totalScore,
    maxScore,
    percentage,
    resultCategory,
    screeningAnswers
) {


    console.log(
        "Saving cognitive screening result..."
    );


    try {


        const response =
            await fetch(
                `${API_BASE_URL}/cognitive-screenings/`,
                {

                    method:
                        "POST",

                    headers: {

                        "Content-Type":
                            "application/json"

                    },

                    body:
                        JSON.stringify({

                            user_id:
                                USER_ID,

                            score:
                                totalScore,

                            max_score:
                                maxScore,

                            percentage:
                                percentage,

                            result_category:
                                resultCategory,

                            answers:
                                screeningAnswers

                        })

                }
            );


        if (
            !response.ok
        ) {


            const errorData =
                await response
                    .json()
                    .catch(
                        function() {

                            return {};

                        }
                    );


            console.error(
                "Screening save failed:",
                errorData
            );


            showSaveStatus(
                false,
                getLanguageData().saveFailed
            );


            return;

        }


        const data =
            await response.json();


        console.log(
            "Screening saved successfully:",
            data
        );


        showSaveStatus(
            true,
            getLanguageData().saved
        );

    }


    catch (error) {


        console.error(
            "Error saving screening:",
            error
        );


        showSaveStatus(
            false,
            getLanguageData().serverFailed
        );

    }

}


